@pytest.mark.unit
def test_engine_is_built_from_configuration() -> None:
    settings = build_settings(
        database_pool_size=7,
        database_max_overflow=3,
        database_pool_timeout_seconds=4.0,
    )

    database = Database(settings)

    assert str(database.engine.url).startswith("postgresql+asyncpg://")
    assert database.engine.pool.size() == 7  # type: ignore[attr-defined]
    assert database.engine.pool._max_overflow == 3  # type: ignore[attr-defined]



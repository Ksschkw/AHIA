@pytest.mark.unit
async def test_unit_of_work_refuses_use_outside_its_context_manager(
    test_database_url: str,
) -> None:
    unit_of_work = Database(build_settings(database_url=test_database_url)).transaction_scope()

    with pytest.raises(PersistenceError, match="outside its context manager"):
        _ = unit_of_work.session_handle

    with pytest.raises(PersistenceError, match="outside its context manager"):
        await unit_of_work.commit()


PROBE_TABLE_NAME = "ahia_transaction_probe"
PROBE_TABLE = Table(PROBE_TABLE_NAME, MetaData(), Column("value", Integer))


@pytest.fixture
async def probe_table(database: Database) -> Any:
    """Create the probe table and drop it afterwards.

    The table is a real one, not a temporary one: a temporary table lives and
    dies with its session, so it cannot demonstrate that a rollback in one
    session is invisible to the next.

    Rows, inserts and counts all go through SQLAlchemy Core constructs rather
    than interpolated SQL strings, so the test exercises the same parameterised
    path production code uses.
    """
    async with database.transaction_scope() as setup_unit_of_work:
        await setup_unit_of_work.session_handle.execute(
            text(f"DROP TABLE IF EXISTS {PROBE_TABLE_NAME}")
        )
        await setup_unit_of_work.session_handle.execute(
            text(f"CREATE TABLE {PROBE_TABLE_NAME} (value INTEGER)")
        )
        await setup_unit_of_work.commit()
    try:
        yield PROBE_TABLE
    finally:
        async with database.transaction_scope() as cleanup_unit_of_work:
            await cleanup_unit_of_work.session_handle.execute(
                text(f"DROP TABLE IF EXISTS {PROBE_TABLE_NAME}")
            )
            await cleanup_unit_of_work.commit()


async def count_probe_rows(database: Database) -> int:
    """Return the number of rows currently visible in the probe table."""
    async with database.transaction_scope() as unit_of_work:
        result = await unit_of_work.session_handle.execute(
            select(func.count()).select_from(PROBE_TABLE)
        )
        return int(result.scalar_one())


@pytest.mark.integration
async def test_commit_persists_rows(database: Database, probe_table: Table) -> None:
    async with database.transaction_scope() as unit_of_work:
        await unit_of_work.session_handle.execute(
            probe_table.insert().values([{"value": 1}, {"value": 2}])
        )
        await unit_of_work.commit()

    assert await count_probe_rows(database) == 2


@pytest.mark.integration
async def test_rollback_discards_rows(database: Database, probe_table: Table) -> None:
    async with database.transaction_scope() as unit_of_work:
        await unit_of_work.session_handle.execute(probe_table.insert().values(value=1))
        await unit_of_work.rollback()

    assert await count_probe_rows(database) == 0


@pytest.mark.integration
async def test_exception_inside_the_block_rolls_back(
    database: Database, probe_table: Table
) -> None:
    class DeliberateFailureError(Exception):
        """Raised to prove the transaction does not survive an exception."""

    with pytest.raises(DeliberateFailureError):
        async with database.transaction_scope() as unit_of_work:
            await unit_of_work.session_handle.execute(probe_table.insert().values(value=1))
            raise DeliberateFailureError

    assert await count_probe_rows(database) == 0


@pytest.mark.integration
async def test_block_that_neither_commits_nor_raises_rolls_back(
    database: Database, probe_table: Table
) -> None:
    """Silence is not consent to write."""
    async with database.transaction_scope() as unit_of_work:
        await unit_of_work.session_handle.execute(probe_table.insert().values(value=1))
        # No commit.

    assert await count_probe_rows(database) == 0


@pytest.mark.integration
async def test_session_is_closed_on_exit(database: Database) -> None:
    unit_of_work = database.transaction_scope()
    async with unit_of_work:
        await unit_of_work.session_handle.execute(text("SELECT 1"))

    with pytest.raises(PersistenceError):
        _ = unit_of_work.session_handle



@pytest.mark.integration
async def test_connectivity_check_returns_false_rather_than_raising() -> None:
    """A readiness probe answers; it does not throw a stack trace at the caller."""
    unreachable = create_async_engine(
        "postgresql+asyncpg://nobody:nobody@127.0.0.1:59999/absent",
        pool_pre_ping=True,
    )
    instance = Database(build_settings(), engine=unreachable)

    assert await instance.check_connectivity() is False

    await instance.dispose()
